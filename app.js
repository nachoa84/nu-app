function inferFavoriteDay(favorite) {
  if (favorite.day) return Number(favorite.day);

  const match = favorite.src.match(/D(\d{2})_/i);
  if (match) return Number(match[1]);

  return 1;
}

function getFavorites() {
  const raw = JSON.parse(localStorage.getItem("favorites") || "[]");
  let changed = false;

  const normalized = raw.map(f => {
    if (!f.day) {
      changed = true;
      return { ...f, day: inferFavoriteDay(f) };
    }
    return { ...f, day: Number(f.day) };
  });

  if (changed) {
    localStorage.setItem("favorites", JSON.stringify(normalized));
  }

  return normalized;
}

