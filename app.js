function applyBackendRoutineState(serverState) {
  if (!serverState) return;

  const localState =
    getRoutineState();

  const openedDays = {};

  Object.entries(
    serverState.openedDays || {}
  ).forEach(([day, timestamp]) => {
    openedDays[day] =
      Number(timestamp);
  });

  localState.currentDay =
    Number(
      serverState.currentDay ||
      localState.currentDay ||
      1
    );

  localState.openedDays =
    openedDays;

  localState.nextUnlockAt =
    serverState.nextUnlockAt
      ? Number(
          serverState.nextUnlockAt
        )
      : null;

  localState.scheduleProfileSignature =
    scheduleProfileSignature();

  saveRoutineState(localState);

  (
    serverState.completedDays || []
  ).forEach(day => {
    localStorage.setItem(
      `day${day}Complete`,
      "1"
    );
  });

  if (!isPreviewMode) {
    selectedDay =
      localState.currentDay;

    localStorage.setItem(
      "selectedDay",
      String(selectedDay)
    );
  }

  renderSelectedDayHeader();
  renderDays();
  renderFavorites();
}

window.addEventListener(
  "backend-state-updated",
  event => {
    applyBackendRoutineState(
      event.detail
    );
  }
);

function getRoutineState() {
  const fallback = {
    currentDay: 1,
    openedDays: {},
    nextUnlockAt: null,
    scheduleProfileSignature: null
  };

  try {
    const saved = JSON.parse(
      localStorage.getItem("routineState") || "null"
    );

    if (!saved) return fallback;

    return {
      currentDay: Number(saved.currentDay || 1),
      openedDays: saved.openedDays || {},
      nextUnlockAt: saved.nextUnlockAt || null,
      scheduleProfileSignature:
        saved.scheduleProfileSignature || null
    };
  } catch (e) {
    return fallback;
  }
}

function saveRoutineState(state) {
  localStorage.setItem(
    "routineState",
    JSON.stringify(state)
  );
}

function getRoutineProfile() {
  try {
    return JSON.parse(
      localStorage.getItem("routineUserProfile") || "null"
    );
  } catch (e) {
    return null;
  }
}

function getDeviceTimezone() {
  try {
    return (
      Intl.DateTimeFormat()
        .resolvedOptions()
        .timeZone ||
      "America/Argentina/Buenos_Aires"
    );
  } catch (e) {
    return "America/Argentina/Buenos_Aires";
  }
}

