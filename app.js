function revealNext() {
  const blocks = currentBlocks();
  if (revealIndex >= blocks.length) return;

  const el = createBlock(blocks[revealIndex]);
  chat.appendChild(el);
  revealIndex++;
  updateProgress();

  setTimeout(() => {
    el.scrollIntoView({
      behavior: "smooth",
      block: "end"
    });
  }, 50);

  if (revealIndex < blocks.length) {
    const delay =
      blocks[revealIndex - 1].type === "media"
        ? 900
        : 700;

    revealTimer = setTimeout(revealNext, delay);
  }
}

