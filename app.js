function getZonedParts(date, timeZone) {
  const formatter =
    new Intl.DateTimeFormat(
      "en-CA",
      {
        timeZone,
        year: "numeric",
        month: "2-digit",
        day: "2-digit",
        hour: "2-digit",
        minute: "2-digit",
        second: "2-digit",
        hourCycle: "h23"
      }
    );

  const parts = {};

  formatter
    .formatToParts(date)
    .forEach(part => {
      if (part.type !== "literal") {
        parts[part.type] =
          Number(part.value);
      }
    });

  return parts;
}

function zonedWallTimeToTimestamp({
  year,
  month,
  day,
  hour,
  minute,
  timeZone
}) {
  const desiredAsUTC =
    Date.UTC(
      year,
      month - 1,
      day,
      hour,
      minute,
      0,
      0
    );

  let guess = desiredAsUTC;

  // Ajuste iterativo para convertir una hora "de pared"
  // en una zona IANA a un timestamp UTC.
  for (let i = 0; i < 4; i++) {
    const actual =
      getZonedParts(
        new Date(guess),
        timeZone
      );

    const actualAsUTC =
      Date.UTC(
        actual.year,
        actual.month - 1,
        actual.day,
        actual.hour,
        actual.minute,
        actual.second || 0,
        0
      );

    const diff =
      desiredAsUTC - actualAsUTC;

    guess += diff;

    if (Math.abs(diff) < 1000) {
      break;
    }
  }

  return guess;
}

function nextUnlockTimestampFromProfile(
  openedAt = Date.now()
) {
  const {
    timezone,
    notificationTime
  } = getScheduleProfile();

  const [hour, minute] =
    notificationTime
      .split(":")
      .map(Number);

  const openedParts =
    getZonedParts(
      new Date(openedAt),
      timezone
    );

  // Calculamos el día calendario siguiente
  // dentro de la zona horaria del usuario.
  const nextCalendar =
    new Date(
      Date.UTC(
        openedParts.year,
        openedParts.month - 1,
        openedParts.day + 1,
        0,
        0,
        0
      )
    );

  return zonedWallTimeToTimestamp({
    year:
      nextCalendar.getUTCFullYear(),
    month:
      nextCalendar.getUTCMonth() + 1,
    day:
      nextCalendar.getUTCDate(),
    hour:
      Number.isFinite(hour)
        ? hour
        : DEFAULT_UNLOCK_HOUR,
    minute:
      Number.isFinite(minute)
        ? minute
        : 0,
    timeZone: timezone
  });
}

function rescheduleNextUnlockFromProfile(
  force = false
) {
  if (isPreviewMode) return;

  const state = getRoutineState();

  if (state.currentDay >= 7) {
    return;
  }

  const openedAt =
    state.openedDays[state.currentDay];

  if (!openedAt) {
    return;
  }

  const signature =
    scheduleProfileSignature();

  if (
    !force &&
    state.scheduleProfileSignature ===
      signature &&
    state.nextUnlockAt
  ) {
    return;
  }

  state.nextUnlockAt =
    nextUnlockTimestampFromProfile(
      Number(openedAt)
    );

  state.scheduleProfileSignature =
    signature;

  saveRoutineState(state);
}

function markCurrentDayOpened() {
  if (isPreviewMode) return;

  const state = getRoutineState();

  if (Number(selectedDay) !== Number(state.currentDay)) {
    return;
  }

  if (!state.openedDays[state.currentDay]) {
    state.openedDays[state.currentDay] = Date.now();

    if (state.currentDay < 7) {
      state.nextUnlockAt =
        nextUnlockTimestampFromProfile(
          state.openedDays[state.currentDay]
        );

      state.scheduleProfileSignature =
        scheduleProfileSignature();
    } else {
      state.nextUnlockAt = null;
      state.scheduleProfileSignature = null;
    }

    saveRoutineState(state);
    renderDays();

    if (window.BackendAPI) {
      window.BackendAPI
        .openDay(state.currentDay)
        .catch(error => {
          console.warn(
            "No se pudo sincronizar la apertura con el backend.",
            error
          );
        });
    }
  }
}

function advanceRoutineIfEligible() {
  if (isPreviewMode) return false;

  const state = getRoutineState();

  if (
    state.currentDay < 7 &&
    state.openedDays[state.currentDay] &&
    state.nextUnlockAt &&
    Date.now() >= Number(state.nextUnlockAt)
  ) {
    state.currentDay += 1;
    state.nextUnlockAt = null;
    state.scheduleProfileSignature = null;

    saveRoutineState(state);

    selectedDay = state.currentDay;

    localStorage.setItem(
      "selectedDay",
      String(selectedDay)
    );

    return true;
  }

  return false;
}

