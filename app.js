function inferFavoriteDay(favorite) {
  if (favorite.day) return Number(favorite.day);

  const match = favorite.src.match(/D(\d{2})_/i);
  if (match) return Number(match[1]);

  return 1;
}

function getFavorites() {
  const raw = JSON.parse(localStorage.getItem("favorites") || "[]");
  let changed = false;

  const normalized = raw.map(f => {
    if (!f.day) {
      changed = true;
      return { ...f, day: inferFavoriteDay(f) };
    }
    return { ...f, day: Number(f.day) };
  });

  if (changed) {
    localStorage.setItem("favorites", JSON.stringify(normalized));
  }

  return normalized;
}

function isFavorite(src, day = selectedDay) {
  return getFavorites().some(
    f => f.src === src && Number(f.day) === Number(day)
  );
}

function updateFavoriteButtons() {
  document.querySelectorAll("[data-favorite-src]").forEach(btn => {
    const src = btn.dataset.favoriteSrc;
    const day = Number(btn.dataset.favoriteDay);

    btn.textContent = isFavorite(src, day)
      ? "♥ Guardado"
      : "♡ Favorito";
  });
}

function saveFavorite(src, label, mediaType, day = selectedDay, url = null) {
  const favs = getFavorites();

  const idx = favs.findIndex(
    f => f.src === src && Number(f.day) === Number(day)
  );

  if (idx >= 0) {
    favs.splice(idx, 1);
    toast("Eliminado de favoritos");
  } else {
    favs.push({
      src,
      label,
      mediaType,
      day: Number(day),
      ...(url ? { url } : {})
    });
    toast("Guardado en favoritos");
  }

  localStorage.setItem("favorites", JSON.stringify(favs));
  renderFavorites();
  updateFavoriteButtons();

  document
    .querySelectorAll(".resource-link-save")
    .forEach(() => {});

  if (!chatWrap.classList.contains("hidden")) {
    const currentScroll = window.scrollY;
    const showingAll = revealIndex >= currentBlocks().length;

    if (showingAll) {
      showAll();
      window.scrollTo(0, currentScroll);
    }
  }
}

async function shareAsset(src, label, mediaType) {
  try {
    const res = await fetch(src);
    const blob = await res.blob();
    const ext = mediaType === "video" ? "mp4" : "jpg";

    const file = new File(
      [blob],
      `${label.replaceAll(" ", "_")}.${ext}`,
      { type: blob.type }
    );

    if (
      navigator.canShare &&
      navigator.canShare({ files: [file] })
    ) {
      await navigator.share({
        files: [file],
        title: label
      });
      return;
    }
  } catch (e) {
    console.error("No se pudo compartir directamente:", e);
  }

  const a = document.createElement("a");
  a.href = src;
  a.download = "";
  a.target = "_blank";
  a.click();

  toast(
    "Tu dispositivo no permite compartir directo desde esta PWA. Se abrió/descargó el archivo."
  );
}

function addLinks(container, links) {
  if (!links || !links.length) return;

  const wrap = document.createElement("div");
  wrap.className = "resource-links";

  links.forEach(link => {
    const row = document.createElement("div");
    row.className = "resource-link-row";

    const a = document.createElement("a");
    a.href = link.url;
    a.target = "_blank";
    a.rel = "noopener";
    a.textContent = link.label;
    a.className = "resource-link-main";

    const favoriteKey = `link:${link.url}`;
    const saved = isFavorite(favoriteKey, selectedDay);

    const save = document.createElement("button");
    save.type = "button";
    save.className = "resource-link-save";
    save.setAttribute(
      "aria-label",
      saved ? "Quitar enlace de guardados" : "Guardar enlace"
    );
    save.innerHTML = saved ? "♥" : "♡";

    save.onclick = () =>
      saveFavorite(
        favoriteKey,
        link.label,
        "link",
        selectedDay,
        link.url
      );

    row.append(a, save);
    wrap.appendChild(row);
  });

  container.appendChild(wrap);
}

